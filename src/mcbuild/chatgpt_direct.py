"""Safe, deterministic geometry requests for ChatGPT -> GitHub Actions -> .schem.

Accepts a *data-only* JSON contract, never arbitrary Python generated by an LLM.
The DSL functions are invoked by trusted project code, not through exec/eval.
"""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any

from mcbuild.dsl.stdlib import make_stdlib
from mcbuild.voxel import VoxelGrid

SCHEMA = "gabcon-block-ops-v1"
MAX_OPERATIONS = 1200
MAX_BLOCKS = 1_000_000
MAX_ESTIMATED_WRITES = 2_000_000
MAX_SINGLE_OPERATION = 1_000_000
MAX_SCHEMATIC_VOLUME = 20_000_000
MAX_COORD = 512
MAX_RADIUS = 64
MAX_HEIGHT = 128

# n: integer position/size, b: Minecraft block registry identifier or block state.
SIGNATURES: dict[str, str] = {
    "set_block": "nnnb",
    "fill": "nnnnnnb",
    "clear": "nnnnnn",
    "walls": "nnnnnnb",
    "floor": "nnnnnb",
    "hollow_box": "nnnnnnb",
    "cylinder": "nnnnnb",
    "sphere": "nnnnb",
    "dome": "nnnnb",
    "line": "nnnnnnb",
    "pyramid": "nnnnnb",
    "cone": "nnnnnb",
    "gable_roof": "nnnnnb",
    "hip_roof": "nnnnnb",
}
BLOCK_NAME = re.compile(r"^(?:[a-z0-9_.-]+:)?[a-z0-9_./-]+(?:\\[[a-z0-9_=,.-]+\\])?$")


class BuildRequestError(ValueError):
    """Invalid or oversized structured ChatGPT construction request."""


def _length(a: int, b: int) -> int:
    return abs(a - b) + 1


def _estimated_writes(op: str, args: list[int | str]) -> int:
    """Conservative bound on primitive iterations, before executing any voxel calls."""
    if op == "set_block":
        return 1
    if op in {"fill", "clear", "hollow_box"}:
        return _length(args[0], args[3]) * _length(args[1], args[4]) * _length(args[2], args[5])
    if op == "walls":
        # x1, z1, x2, z2, y1, y2
        return (
            2
            * (_length(args[0], args[2]) + _length(args[1], args[3]))
            * _length(args[4], args[5])
        )
    if op == "floor":
        # x1, z1, x2, z2, y
        return _length(args[0], args[2]) * _length(args[1], args[3])
    if op == "cylinder":
        # cx,cz,y,height,r
        return (2 * args[4] + 1) ** 2 * args[3]
    if op in {"sphere", "dome"}:
        return (2 * args[3] + 1) ** 3
    if op == "line":
        return max(abs(args[3] - args[0]), abs(args[4] - args[1]), abs(args[5] - args[2])) + 1
    if op in {"pyramid", "cone"}:
        # cx,cz,y,base_or_radius,height
        return (2 * args[3] + 3) ** 2 * args[4]
    if op in {"gable_roof", "hip_roof"}:
        return (_length(args[0], args[2]) + 2) * (_length(args[1], args[3]) + 2)
    raise BuildRequestError(f"Opération inconnue : {op}")


def _validate_shape(op: str, args: list[int | str]) -> None:
    if op == "cylinder":
        if not 1 <= args[3] <= MAX_HEIGHT or not 0 <= args[4] <= MAX_RADIUS:
            raise BuildRequestError("cylinder : hauteur ou rayon hors limites.")
    elif op in {"sphere", "dome"}:
        if not 0 <= args[3] <= MAX_RADIUS:
            raise BuildRequestError(f"{op} : rayon hors limites.")
    elif op in {"pyramid", "cone"}:
        if not 0 <= args[3] <= MAX_RADIUS or not 1 <= args[4] <= MAX_HEIGHT:
            raise BuildRequestError(f"{op} : base/rayon ou hauteur hors limites.")


def validate_request(request: Any) -> tuple[str, int, list[tuple[str, list[int | str]]]]:
    """Validate everything before executing the first operation."""
    if not isinstance(request, dict) or request.get("schema") != SCHEMA:
        raise BuildRequestError(f"Le JSON doit déclarer schema={SCHEMA}.")
    if set(request) - {"schema", "name", "seed", "operations"}:
        raise BuildRequestError("Champs JSON inconnus. Attendus : schema, name, seed, operations.")
    name = request.get("name", "construction-chatgpt")
    if not isinstance(name, str) or not 1 <= len(name) <= 80 or any(ord(c) < 32 for c in name):
        raise BuildRequestError("Le nom de construction est invalide.")
    seed = request.get("seed", 0)
    if type(seed) is not int or not 0 <= seed < 2**31:
        raise BuildRequestError("La seed doit être un entier entre 0 et 2147483647.")
    ops = request.get("operations")
    if not isinstance(ops, list) or not 1 <= len(ops) <= MAX_OPERATIONS:
        raise BuildRequestError(f"Il faut de 1 à {MAX_OPERATIONS} opérations.")
    validated: list[tuple[str, list[int | str]]] = []
    total = 0
    for i, entry in enumerate(ops, 1):
        if not isinstance(entry, dict) or set(entry) != {"op", "args"}:
            raise BuildRequestError(f"Opération {i} : objet op/args requis.")
        op = entry["op"]
        signature = SIGNATURES.get(op) if isinstance(op, str) else None
        args = entry["args"]
        if signature is None or not isinstance(args, list) or len(args) != len(signature):
            raise BuildRequestError(f"Opération {i} : nom ou nombre d'arguments invalide.")
        for arg, kind in zip(args, signature, strict=True):
            if kind == "n":
                if type(arg) is not int or abs(arg) > MAX_COORD:
                    raise BuildRequestError(f"Opération {i} : coordonnées/dimensions entières exigées (±{MAX_COORD}).")
            elif not isinstance(arg, str) or not 1 <= len(arg) <= 180 or not BLOCK_NAME.fullmatch(arg):
                raise BuildRequestError(f"Opération {i} : identifiant de bloc invalide.")
        _validate_shape(op, args)
        cost = _estimated_writes(op, args)
        if cost > MAX_SINGLE_OPERATION:
            raise BuildRequestError(f"Opération {i} trop volumineuse ({cost:,} itérations estimées).")
        total += cost
        if total > MAX_ESTIMATED_WRITES:
            raise BuildRequestError(f"Trop d'opérations ({total:,} écritures estimées).")
        validated.append((op, args))
    return name, seed, validated


def build_request(request: Any) -> tuple[VoxelGrid, dict[str, Any]]:
    """Build data-only operations with the trusted DSL, enforcing size/volume budgets."""
    name, seed, ops = validate_request(request)
    grid = VoxelGrid()
    ns = make_stdlib(grid, seed=seed)
    for i, (op, args) in enumerate(ops, 1):
        try:
            ns[op](*args)
        except Exception as exc:
            raise BuildRequestError(f"Opération {i} ({op}) : {exc}") from exc
        if len(grid) > MAX_BLOCKS:
            raise BuildRequestError(f"Construction trop grande : maximum {MAX_BLOCKS:,} blocs.")
    if not len(grid) or grid.bounds is None:
        raise BuildRequestError("Le blueprint n'a placé aucun bloc.")
    lower, upper = grid.bounds
    dims = tuple(upper[i] - lower[i] + 1 for i in range(3))
    volume = dims[0] * dims[1] * dims[2]
    if volume > MAX_SCHEMATIC_VOLUME:
        raise BuildRequestError(f"Volume englobant trop grand ({volume:,} cases, max {MAX_SCHEMATIC_VOLUME:,}).")
    stats = {
        "name": name, "seed": seed, "schema": SCHEMA,
        "block_count": len(grid), "operation_count": len(ops),
        "bounds": [list(lower), list(upper)], "dimensions": list(dims),
        "bounding_volume": volume, "format": "Sponge Schematic v3",
        "minecraft": "Java 1.21.1",
    }
    return grid, stats


def read_request(path: str | Path) -> Any:
    """Reject giant requests before parsing."""
    p = Path(path)
    if p.stat().st_size > 250_000:
        raise BuildRequestError("Requête JSON trop volumineuse (maximum 250 Ko).")
    try:
        return json.loads(p.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        raise BuildRequestError(f"JSON invalide (ligne {exc.lineno}) : {exc.msg}") from exc
